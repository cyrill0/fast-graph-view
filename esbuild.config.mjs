import esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import builtins from 'builtin-modules';

const prod = process.argv.includes('production');
const watch = process.argv.includes('--watch');

const common = {
  bundle: true,
  target: 'es2020',
  legalComments: 'none',
  minify: prod,
  sourcemap: prod ? false : 'linked',
};

/** The force simulation is bundled standalone and embedded as a string, so the
 *  plugin ships one main.js while still running physics in a real Worker. */
async function buildWorkerSource() {
  const result = await esbuild.build({
    ...common,
    entryPoints: ['src/layout/sim-worker.ts'],
    outfile: 'sim-worker.js',
    format: 'iife',
    platform: 'neutral',
    sourcemap: false,
    write: false,
  });
  const code = result.outputFiles[0].text;
  fs.mkdirSync('src/generated', { recursive: true });
  fs.writeFileSync(
    'src/generated/worker-source.ts',
    '// Generated by esbuild.config.mjs - do not edit. Source: src/layout/sim-worker.ts\n' +
      'export const WORKER_SOURCE = ' +
      JSON.stringify(code) +
      ';\n',
  );
  return code.length;
}

async function main() {
  const workerBytes = await buildWorkerSource();
  const options = {
    ...common,
    external: ['obsidian', 'electron', '@codemirror/*', '@lezer/*', ...builtins],
    define: { 'process.env.NODE_ENV': prod ? '"production"' : '"development"' },
    platform: 'browser',
    format: 'cjs',
    entryPoints: ['src/main.ts'],
    outfile: 'main.js',
    logLimit: 0,
  };

  if (watch) {
    const ctx = await esbuild.context(options);
    await ctx.watch();
    console.log(`watching (worker ${workerBytes} bytes embedded)`);
    return;
  }

  await esbuild.build(options);
  const size = fs.statSync(path.resolve('main.js')).size;
  console.log(
    `${prod ? 'production' : 'dev'} build: main.js ${(size / 1024).toFixed(1)} KB ` +
      `(worker ${workerBytes} bytes)`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
