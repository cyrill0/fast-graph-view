import esbuild from 'esbuild';
import fs from 'node:fs';
import { builtinModules } from 'node:module';
import path from 'node:path';
import process from 'node:process';

const prod = process.argv.includes('production');
const watch = process.argv.includes('--watch');
const nodeBuiltins = builtinModules.flatMap((name) => [name, `node:${name}`]);

const common = {
  bundle: true,
  target: 'es2020',
  legalComments: 'none',
  minify: prod,
  sourcemap: prod ? false : 'linked',
};

/** The force simulation is bundled standalone and embedded as a string, so the
 *  plugin ships one main.js while still running physics in a real Worker. */
async function buildWorkerSource() {
  const result = await esbuild.build({
    ...common,
    entryPoints: ['src/layout/sim-worker.ts'],
    outfile: 'sim-worker.js',
    format: 'iife',
    platform: 'neutral',
    sourcemap: false,
    write: false,
  });
  const code = result.outputFiles[0].text;
  const targetFile = 'src/generated/worker-source.ts';
  const nextContent =
    '// Generated by esbuild.config.mjs - do not edit. Source: src/layout/sim-worker.ts\n' +
    'export const WORKER_SOURCE = ' +
    JSON.stringify(code) +
    ';\n';
  fs.mkdirSync('src/generated', { recursive: true });
  const prevContent = fs.existsSync(targetFile) ? fs.readFileSync(targetFile, 'utf8') : '';
  if (prevContent !== nextContent) {
    fs.writeFileSync(targetFile, nextContent);
  }
  return code.length;
}

async function main() {
  let workerBytes = await buildWorkerSource();
  const workerPlugin = {
    name: 'embed-sim-worker',
    setup(build) {
      build.onStart(async () => {
        workerBytes = await buildWorkerSource();
      });
    },
  };
  const options = {
    ...common,
    external: ['obsidian', 'electron', '@codemirror/*', '@lezer/*', ...nodeBuiltins],
    define: { 'process.env.NODE_ENV': prod ? '"production"' : '"development"' },
    platform: 'browser',
    format: 'cjs',
    entryPoints: ['src/main.ts'],
    outfile: 'main.js',
    logLimit: 0,
    plugins: [workerPlugin],
  };

  if (watch) {
    const ctx = await esbuild.context(options);
    await ctx.watch();
    console.log(`watching (worker ${workerBytes} bytes embedded)`);
    return;
  }

  await esbuild.build(options);
  const size = fs.statSync(path.resolve('main.js')).size;
  console.log(
    `${prod ? 'production' : 'dev'} build: main.js ${(size / 1024).toFixed(1)} KB ` +
      `(worker ${workerBytes} bytes)`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
